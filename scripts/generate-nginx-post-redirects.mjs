import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const POSTS_DIR = path.resolve("src/content/post");
const OUTPUT_FILE = path.resolve("dist/.nginx-post-redirects.conf");

function parseFrontmatter(source, fileName) {
	const frontmatter = source.match(/^---\n([\s\S]*?)\n---/u)?.[1];
	if (!frontmatter) throw new Error(`Missing frontmatter in ${fileName}`);

	const slug = frontmatter.match(/^slug:\s*["']([^"']+)["']\s*$/mu)?.[1];
	if (!slug) throw new Error(`Missing canonical slug in ${fileName}`);

	const legacyValue = frontmatter.match(/^legacySlugs:\s*(\[[^\n]*\])\s*$/mu)?.[1] ?? "[]";
	const legacySlugs = JSON.parse(legacyValue);
	if (!Array.isArray(legacySlugs) || legacySlugs.some((item) => typeof item !== "string")) {
		throw new Error(`Invalid legacySlugs in ${fileName}`);
	}

	return { slug, legacySlugs };
}

function quoteNginxPath(value) {
	if (/[\r\n]/u.test(value)) throw new Error(`Unsafe newline in redirect path: ${value}`);
	return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

function addRedirect(rules, source, destination) {
	if (source === destination) return;
	const existing = rules.get(source);
	if (existing && existing !== destination) {
		throw new Error(`Conflicting redirect for ${source}: ${existing} vs ${destination}`);
	}
	rules.set(source, destination);
}

const files = (await readdir(POSTS_DIR)).filter(
	(fileName) => fileName.endsWith(".md") && !fileName.endsWith(".en.md"),
);
const rules = new Map();

for (const fileName of files) {
	const entryId = fileName.slice(0, -3);
	const source = await readFile(path.join(POSTS_DIR, fileName), "utf8");
	const { slug, legacySlugs } = parseFrontmatter(source, fileName);
	const aliases = [...new Set([entryId, ...legacySlugs])].filter((alias) => alias !== slug);

	for (const alias of aliases) {
		addRedirect(rules, `/zh/posts/${alias}`, `/zh/posts/${slug}`);
		addRedirect(rules, `/en/posts/${alias}`, `/en/posts/${slug}`);
	}

	for (const alias of new Set([slug, entryId, ...legacySlugs])) {
		addRedirect(rules, `/posts/${alias}`, `/zh/posts/${slug}`);
	}
}

const lines = [
	"# Generated by scripts/generate-nginx-post-redirects.mjs. Do not edit manually.",
	`# ${files.length} posts; ${rules.size} permanent redirects.`,
	...Array.from(rules.entries())
		.sort(([left], [right]) => left.localeCompare(right, "en"))
		.map(
			([source, destination]) =>
				`location = ${quoteNginxPath(source)} { return 301 ${quoteNginxPath(destination)}; }`,
		),
	"",
];

await writeFile(OUTPUT_FILE, lines.join("\n"));
console.log(`Generated ${rules.size} permanent redirects for ${files.length} posts.`);
